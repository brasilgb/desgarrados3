<?php

use App\Http\Controllers\Admin\CategoryController;
use App\Http\Controllers\Admin\CollectionController;
use App\Http\Controllers\Admin\ContactMessageController;
use App\Http\Controllers\Admin\DashboardController;
use App\Http\Controllers\Admin\MediaController;
use App\Http\Controllers\Admin\PortalSettingsController;
use App\Http\Controllers\Admin\ProductionGuideAdminController;
use App\Http\Controllers\Admin\PublicationController;
use App\Http\Controllers\Admin\PublicationRevisionController;
use App\Http\Controllers\Admin\RegionalEventAdminController;
use App\Http\Controllers\Admin\RegionalIntegrationController;
use App\Http\Controllers\Admin\RegionalToolSettingsController;
use App\Http\Controllers\Admin\RuralCalendarEntryController;
use App\Http\Controllers\Admin\SayingController;
use App\Http\Controllers\Admin\SeriesController;
use App\Http\Controllers\Admin\SitePageController;
use App\Http\Controllers\Admin\StorySubmissionController;
use App\Http\Controllers\Admin\TermsVersionController;
use App\Http\Controllers\Admin\UserController;
use Illuminate\Support\Facades\Route;

Route::middleware(['auth', 'verified', 'active', 'can:access-admin'])->prefix('admin')->name('admin.')->group(function () {
    Route::get('/', DashboardController::class)->name('dashboard');
    Route::get('submissions', [StorySubmissionController::class, 'index'])->name('submissions.index');
    Route::get('submissions/{submission}', [StorySubmissionController::class, 'show'])->name('submissions.show');
    Route::get('terms-versions/{termsVersion}', [TermsVersionController::class, 'show'])->name('terms-versions.show');
    Route::get('submissions/{submission}/photo', [StorySubmissionController::class, 'photo'])->name('submissions.photo');
    Route::post('submissions/{submission}/photo/incorporate', [StorySubmissionController::class, 'incorporatePhoto'])->name('submissions.photo.incorporate');
    Route::post('submissions/{submission}/approve', [StorySubmissionController::class, 'approve'])->name('submissions.approve');
    Route::post('submissions/{submission}/reject', [StorySubmissionController::class, 'reject'])->name('submissions.reject');
    Route::post('submissions/{submission}/convert', [StorySubmissionController::class, 'convert'])->name('submissions.convert');
    Route::post('publications/preview', [PublicationController::class, 'preview'])->name('publications.preview');
    Route::post('publications/bulk', [PublicationController::class, 'bulkUpdate'])->name('publications.bulk');
    Route::get('publications/municipalities', [PublicationController::class, 'municipalities'])->name('publications.municipalities');
    Route::get('publications/{publication}/revisions', [PublicationRevisionController::class, 'index'])->name('publications.revisions.index');
    Route::post('publications/{publication}/revisions/{revision}/restore', [PublicationRevisionController::class, 'restore'])->name('publications.revisions.restore');
    Route::put('publications/{publication}/autosave', [PublicationController::class, 'autosave'])->name('publications.autosave');
    Route::post('publications/{publication}/duplicate', [PublicationController::class, 'duplicate'])->name('publications.duplicate');
    Route::resource('publications', PublicationController::class)->except('show');
    Route::get('categories', [CategoryController::class, 'index'])->name('categories.index');
    Route::post('categories', [CategoryController::class, 'store'])->name('categories.store');
    Route::delete('categories/{category}', [CategoryController::class, 'destroy'])->name('categories.destroy');
    Route::get('collections', [CollectionController::class, 'index'])->name('collections.index');
    Route::post('collections', [CollectionController::class, 'store'])->name('collections.store');
    Route::patch('collections/{collection}', [CollectionController::class, 'update'])->name('collections.update');
    Route::delete('collections/{collection}', [CollectionController::class, 'destroy'])->name('collections.destroy');
    Route::get('series', [SeriesController::class, 'index'])->name('series.index');
    Route::post('series', [SeriesController::class, 'store'])->name('series.store');
    Route::get('sayings', [SayingController::class, 'index'])->name('sayings.index');
    Route::post('sayings', [SayingController::class, 'store'])->name('sayings.store');
    Route::put('sayings/{saying}', [SayingController::class, 'update'])->name('sayings.update');
    Route::delete('sayings/{saying}', [SayingController::class, 'destroy'])->name('sayings.destroy');
    Route::middleware('can:manage-users')->group(function () {
        Route::get('campeira', [RegionalToolSettingsController::class, 'edit'])->name('campeira.edit');
        Route::put('campeira', [RegionalToolSettingsController::class, 'update'])->name('campeira.update');
        Route::get('integrations', [RegionalIntegrationController::class, 'index'])->name('integrations.index');
        Route::put('integrations/{integration}', [RegionalIntegrationController::class, 'update'])->name('integrations.update');
        Route::post('integrations/{integration}/sync', [RegionalIntegrationController::class, 'sync'])->middleware('throttle:2,60')->name('integrations.sync');
        Route::get('settings/portal', [PortalSettingsController::class, 'edit'])->name('settings.portal.edit');
        Route::put('settings/portal', [PortalSettingsController::class, 'update'])->name('settings.portal.update');
        Route::get('site-pages', [SitePageController::class, 'index'])->name('site-pages.index');
        Route::get('site-pages/create', [SitePageController::class, 'create'])->name('site-pages.create');
        Route::post('site-pages', [SitePageController::class, 'store'])->name('site-pages.store');
        Route::get('site-pages/{sitePage}/edit', [SitePageController::class, 'edit'])->name('site-pages.edit');
        Route::put('site-pages/{sitePage}', [SitePageController::class, 'update'])->name('site-pages.update');
        Route::get('contact-messages', [ContactMessageController::class, 'index'])->name('contact-messages.index');
        Route::patch('contact-messages/{contactMessage}/read', [ContactMessageController::class, 'markRead'])->name('contact-messages.read');
        Route::delete('contact-messages/{contactMessage}', [ContactMessageController::class, 'destroy'])->name('contact-messages.destroy');
    });
    Route::resource('rural-calendar', RuralCalendarEntryController::class)->except('show')->names('rural-calendar');
    Route::get('regional-events', [RegionalEventAdminController::class, 'index'])->name('regional-events.index');
    Route::get('regional-events/create', [RegionalEventAdminController::class, 'create'])->name('regional-events.create');
    Route::post('regional-events', [RegionalEventAdminController::class, 'store'])->name('regional-events.store');
    Route::get('regional-events/{event}/edit', [RegionalEventAdminController::class, 'edit'])->name('regional-events.edit');
    Route::put('regional-events/{event}', [RegionalEventAdminController::class, 'update'])->name('regional-events.update');
    Route::post('regional-events/{event}/duplicate', [RegionalEventAdminController::class, 'duplicate'])->name('regional-events.duplicate');
    Route::delete('regional-events/{event}', [RegionalEventAdminController::class, 'destroy'])->name('regional-events.destroy');
    Route::resource('production-guides', ProductionGuideAdminController::class)->except('show')->names('production-guides');
    Route::get('media', [MediaController::class, 'index'])->name('media.index');
    Route::get('media/{media}/file', [MediaController::class, 'file'])->name('media.file');
    Route::post('media', [MediaController::class, 'store'])->name('media.store');
    Route::delete('media/{media}', [MediaController::class, 'destroy'])->name('media.destroy');

    Route::middleware('can:manage-users')->group(function () {
        Route::resource('users', UserController::class)->except(['show', 'destroy']);
        Route::post('users/{user}/password-reset', [UserController::class, 'sendPasswordReset'])->middleware('throttle:3,60')->name('users.password-reset');
    });
});
